"""Build/check the local manual Grok reference. No network or account actions."""

import argparse
import hashlib
import posixpath
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs/grok/agent-kit-reference.md"
DOCS = (
    "AGENTS.md", "docs/team-policy.md", "docs/team-workflow.md",
    "docs/handoff-templates.md", "docs/skills-catalog.md",
    "docs/technote.md", "docs/technote-reference.md",
    "docs/template-application-acceptance.md", "docs/tasks/README.md",
    "docs/engineering/skill-usage/README.md",
    "docs/project-context.md", "docs/project-plan.md",
    "LICENSE",
)


def read_source(relative):
    relative_path = Path(relative)
    path = ROOT / relative_path
    if (relative_path.is_absolute() or ".." in relative_path.parts
            or not path.resolve().is_relative_to(ROOT.resolve()) or any(
                (ROOT / Path(*relative_path.parts[:i])).is_symlink()
                for i in range(1, len(relative_path.parts) + 1))):
        raise ValueError(f"Unsafe source: {relative}")
    return path.read_bytes()


def sources():
    paths = list(DOCS)
    paths += sorted(str(p.relative_to(ROOT)) for p in (ROOT / ".agents").rglob("*")
                    if p.is_file() and (p.suffix == ".md" or p.name == "ADDY-AGENT-SKILLS-LICENSE"))
    paths += sorted(str(p.relative_to(ROOT)) for p in (ROOT / "docs/roles").glob("*.md"))
    return {p: read_source(p) for p in paths}


def anchor(path):
    return "source-" + hashlib.sha256(path.encode()).hexdigest()[:16]


def portable_links(body, source, included):
    # Rewrite prose links only; code/command examples retain their original text.
    def replace(match):
        label, target = match.groups()
        if re.match(r"[a-zA-Z][a-zA-Z0-9+.-]*:", target) or target.startswith("//"):
            return match.group(0)
        file = target.split("#", 1)[0]
        resolved = posixpath.normpath(posixpath.join(posixpath.dirname(source), file)) if file else source
        if resolved in included:
            return f"[{label}](#{anchor(resolved)})"
        return f"{label} (`{resolved}`; external to this reference)"

    lines, fence = [], None
    for line in body.splitlines(keepends=True):
        marker = re.match(r"^\s*(`{3,}|~{3,})", line)
        if marker:
            token = marker.group(1)
            if fence is None:
                fence = token
            elif token[0] == fence[0] and len(token) >= len(fence):
                fence = None
            lines.append(line)
        elif fence:
            lines.append(line)
        else:
            lines.append(re.sub(r"\[([^\]\n]+)\]\(([^)\s]+)\)", replace, line))
    return "".join(lines)


def render():
    content = sources()
    digest = hashlib.sha256()
    for path, data in {**content, "scripts/export_grok.py": read_source("scripts/export_grok.py")}.items():
        digest.update(path.encode() + b"\0" + data + b"\0")
    chunks = [
        "# Agent Kit — manual Grok reference\n\n",
        f"Source revision: `sha256:{digest.hexdigest()}` (source snapshot, not a Git commit).\n\n",
        "Generated by `python3 scripts/export_grok.py`; do not edit this export. "
        "Check freshness with `python3 scripts/export_grok.py --check` before use.\n\n",
        "## Consumer web/app boundary\n\n"
        "This attachment is reference material for a human-started Grok chat. "
        "It registers no native skills or subagents and grants no local repository, shell or account access. "
        "Planner, implementer and reviewer are conversational roles in this context. "
        "Use the relevant skill section as guidance; do not claim automatic discovery/activation. "
        "Use the human's requested language. Project instructions and actual runtime controls still apply.\n\n"
        "Embedded source paths identify sections, not files Grok has read from disk. "
        "Prose links to embedded documents go to their source section; original subsection names can be searched there. "
        "Code examples and tool-specific rules describe their named environments; they do not provide tools here. "
        "External-to-reference paths, project sources, current state and evidence must be supplied separately when needed. "
        "Never fabricate file edits, saved journals, command results, approval, visual verification or deployment. "
        "Without authorized write tools, report proposed changes and unsaved notes in chat. "
        "The blank project templates carry no project definition or approval. "
        "Kit maintenance tasks, approvals, journals and current project state are deliberately excluded.\n\n",
        "## Source inventory\n\nPath | Original SHA-256\n--- | ---\n",
    ]
    for path, data in content.items():
        chunks.append(f"`{path}` | `{hashlib.sha256(data).hexdigest()}`\n")
    chunks.append(
        "\nUpstream engineering content: https://github.com/addyosmani/agent-skills/tree/"
        "1401c8b8030e023baeebb31781a6653fe8e93026 — locally adapted under MIT. "
        "Both kit and upstream license notices are embedded below. "
        "The repository's docs/skills-manifest.json retains per-file provenance.\n"
    )
    for path, data in content.items():
        chunks.append(f'\n---\n\n<a id="{anchor(path)}"></a>\n\n## Source: `{path}`\n\n')
        body = data.decode("utf-8")
        if path == "docs/tasks/README.md":
            # The reusable checkpoint guidance precedes kit-maintenance history.
            body = body.split("\nTASK-001 through TASK-007", 1)[0]
        if path.endswith("SKILL.md"):
            # Frontmatter is metadata here, not a registered skill declaration.
            metadata, body = body.split("---", 2)[1:]
            chunks.append("Source skill metadata:\n\n```yaml\n" + metadata.strip() + "\n```\n\n")
        chunks.append(portable_links(body, path, content).rstrip() + "\n")
    return "".join(chunks)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Read-only freshness check")
    args = parser.parse_args()
    rendered = render()
    if OUTPUT.is_symlink() or not OUTPUT.parent.resolve().is_relative_to(ROOT.resolve()):
        raise SystemExit("Unsafe export destination")
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != rendered:
            raise SystemExit("STALE: regenerate with python3 scripts/export_grok.py")
        print("PASS: Grok reference matches current source snapshot")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(rendered)
        print(f"Generated {OUTPUT.relative_to(ROOT)} ({len(rendered.encode())} bytes)")


if __name__ == "__main__":
    main()
